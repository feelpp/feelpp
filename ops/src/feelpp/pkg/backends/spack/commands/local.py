DEFAULT_SPACK_URL = "https://github.com/spack/spack.git"
DEFAULT_SPACK_PACKAGES_URL = "https://github.com/spack/spack-packages.git"


def _add_repo_root_argument(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("--repo-root", help="Path to the Feel++ repository root")


def _add_local_path_arguments(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("--spack-root", help="Spack checkout root")
    parser.add_argument("--user-config-path", help="SPACK_USER_CONFIG_PATH")
    parser.add_argument("--user-cache-path", help="SPACK_USER_CACHE_PATH")


def _clone_command(url: str, destination: Path, ref: str | None) -> list[str]:
    command = ["git", "clone", "--depth", "1"]
    if ref:
        command.extend(["--branch", ref])
    command.extend([url, str(destination)])
    return command


def _write_yaml_file(
    path: Path,
    payload: dict,
    *,
    force: bool,
    dry_run: bool,
) -> str:
    if path.exists() and not force:
        return "kept"
    if not dry_run:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(yaml.safe_dump(payload, sort_keys=False), encoding="utf-8")
    return "would_write" if dry_run else "written"


def _setup_script(
    *,
    repo_root: Path,
    spack_root: Path,
    user_config_path: Path,
    user_cache_path: Path,
) -> str:
    return "\n".join(
        [
            "# Generated by fpp-spack init.",
            f"export FEELPP_REPO_ROOT={shell_quote(repo_root)}",
            f"export SPACK_ROOT={shell_quote(spack_root)}",
            f"export SPACK_USER_CONFIG_PATH={shell_quote(user_config_path)}",
            f"export SPACK_USER_CACHE_PATH={shell_quote(user_cache_path)}",
            'if [ -f "$SPACK_ROOT/share/spack/setup-env.sh" ]; then',
            '  . "$SPACK_ROOT/share/spack/setup-env.sh"',
            "fi",
            "",
        ]
    )


def _write_text_file(path: Path, content: str, *, force: bool, dry_run: bool) -> str:
    if path.exists() and not force:
        return "kept"
    if not dry_run:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    return "would_write" if dry_run else "written"


def command_spack_init(args: argparse.Namespace) -> int:
    repo_root = resolve_repo_root(args.repo_root)
    metadata_root = spack_metadata_root(repo_root)
    user_config_path = resolve_user_config_path(repo_root, args.user_config_path)
    user_cache_path = resolve_user_cache_path(repo_root, args.user_cache_path)
    spack_root = resolve_spack_root(repo_root, args.spack_root)
    spack_packages_root = (
        Path(args.spack_packages_root).expanduser().resolve()
        if args.spack_packages_root
        else user_cache_path / "spack-packages"
    )

    created_dirs = [
        user_config_path,
        user_cache_path,
        user_cache_path / "source-cache",
        user_cache_path / "misc-cache",
        user_cache_path / "views",
    ]
    if not args.dry_run:
        for directory in created_dirs:
            directory.mkdir(parents=True, exist_ok=True)

    commands: list[list[str]] = []
    if args.install_spack and not (spack_root / "bin" / "spack").is_file():
        commands.append(_clone_command(args.spack_url, spack_root, args.spack_ref))
    if args.install_spack_packages and not spack_packages_root.is_dir():
        commands.append(_clone_command(args.spack_packages_url, spack_packages_root, args.spack_packages_ref))

    for command in commands:
        if args.dry_run:
            continue
        try:
            run_checked(command)
        except subprocess.CalledProcessError as exc:
            raise RuntimeError(f"command failed: {format_command(command)}") from exc

    config_payload = {
        "config": {
            "build_jobs": args.build_jobs,
            "source_cache": str(user_cache_path / "source-cache"),
            "misc_cache": str(user_cache_path / "misc-cache"),
            "install_tree": {
                "root": str(user_cache_path / "install"),
                "padded_length": args.padded_length,
            },
        }
    }
    config_status = _write_yaml_file(
        user_config_path / "config.yaml",
        config_payload,
        force=args.force,
        dry_run=args.dry_run,
    )
    setup_status = _write_text_file(
        user_config_path / "feelpp-spack-setup.sh",
        _setup_script(
            repo_root=repo_root,
            spack_root=spack_root,
            user_config_path=user_config_path,
            user_cache_path=user_cache_path,
        ),
        force=args.force,
        dry_run=args.dry_run,
    )

    payload = {
        "repo_root": str(repo_root),
        "spack_metadata_root": str(metadata_root),
        "spack_root": str(spack_root),
        "spack_packages_root": str(spack_packages_root),
        "spack_user_config_path": str(user_config_path),
        "spack_user_cache_path": str(user_cache_path),
        "created_dirs": [str(path) for path in created_dirs],
        "git_commands": [format_command(command) for command in commands],
        "files": {
            "config": {
                "path": str(user_config_path / "config.yaml"),
                "status": config_status,
            },
            "setup_script": {
                "path": str(user_config_path / "feelpp-spack-setup.sh"),
                "status": setup_status,
            },
        },
        "commands": {
            "setup": f"source {shell_quote(user_config_path / 'feelpp-spack-setup.sh')}",
            "activate_openmpi": 'eval "$(fpp-spack activate openmpi)"',
        },
        "dry_run": args.dry_run,
    }
    print(json.dumps(payload, indent=2))
    return 0


def _doctor_check(name: str, status: str, detail: str, *, hint: str | None = None) -> dict[str, str]:
    payload = {"name": name, "status": status, "detail": detail}
    if hint:
        payload["hint"] = hint
    return payload


def _print_doctor_human(payload: dict[str, object]) -> None:
    summary = payload["summary"]
    if not isinstance(summary, dict):
        raise RuntimeError("invalid doctor summary payload")

    state = "ok" if payload["ok"] else "failed"
    print(f"Feel++ Spack doctor: {state}")
    print(f"Repo root: {payload['repo_root']}")
    print(f"Spack metadata: {payload['spack_metadata_root']}")
    print(f"Spack root: {payload['spack_root']}")
    print(f"SPACK_USER_CONFIG_PATH: {payload['spack_user_config_path']}")
    print(f"SPACK_USER_CACHE_PATH: {payload['spack_user_cache_path']}")
    print("")
    print("Checks:")
    for check in payload["checks"]:
        if not isinstance(check, dict):
            continue
        status = str(check["status"]).upper()
        print(f"  [{status}] {check['name']}: {check['detail']}")
        hint = check.get("hint")
        if hint:
            print(f"        hint: {hint}")

    environment = payload.get("environment")
    if isinstance(environment, dict):
        print("")
        print("Environment:")
        print(f"  name: {environment['name']}")
        print(f"  root: {environment['environment_root']}")
        views = environment.get("views", [])
        if isinstance(views, list):
            for view in views:
                if not isinstance(view, dict):
                    continue
                exists = view.get("exists")
                state = "exists" if exists is True else "missing" if exists is False else "unknown"
                print(f"  view {view['name']}: {view['path']} ({state})")

    print("")
    print(
        "Summary: "
        f"{summary['errors']} error(s), "
        f"{summary['warnings']} warning(s), "
        f"strict={summary['strict']}"
    )


def command_spack_doctor(args: argparse.Namespace) -> int:
    repo_root = resolve_repo_root(args.repo_root)
    metadata_root = spack_metadata_root(repo_root)
    root = environments_root(repo_root)
    user_config_path = resolve_user_config_path(repo_root, args.user_config_path)
    user_cache_path = resolve_user_cache_path(repo_root, args.user_cache_path)
    spack_root = resolve_spack_root(repo_root, args.spack_root)

    checks: list[dict[str, str]] = []
    checks.append(
        _doctor_check(
            "metadata_root",
            "ok" if metadata_root.is_dir() else "error",
            str(metadata_root),
            hint="Expected Feel++ Spack metadata under packaging/spack",
        )
    )
    checks.append(
        _doctor_check(
            "environments_root",
            "ok" if root.is_dir() else "error",
            str(root),
        )
    )

    manifests: list[Path] = []
    if root.is_dir():
        manifests = _environment_manifests(root)
        checks.append(
            _doctor_check(
                "environment_manifests",
                "ok" if manifests else "error",
                f"{len(manifests)} manifest(s) found",
            )
        )
        for manifest in manifests:
            try:
                _load_manifest_payload(manifest)
                checks.append(_doctor_check(f"manifest:{_environment_name(root, manifest)}", "ok", str(manifest)))
            except Exception as exc:  # noqa: BLE001
                checks.append(_doctor_check(f"manifest:{manifest}", "error", str(exc)))

    overlay_repo = metadata_root / "repo" / "spack_repo" / "feelpp" / "repo.yaml"
    checks.append(
        _doctor_check(
            "local_overlay_repo",
            "ok" if overlay_repo.is_file() else "warn",
            str(overlay_repo),
            hint="The shared environments can still use upstream packages when no local overlay is needed.",
        )
    )

    executable = spack_executable(spack_root)
    if executable is None or not executable.exists():
        checks.append(
            _doctor_check(
                "spack_executable",
                "error",
                str(executable) if executable is not None else "not found",
                hint="Run fpp-spack init --install-spack or set SPACK_ROOT/PATH.",
            )
        )
    else:
        completed = subprocess.run(
            [str(executable), "--version"],
            check=False,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            env={
                **dict(os.environ),
                **spack_env_overrides(
                    user_config_path=user_config_path,
                    user_cache_path=user_cache_path,
                ),
            },
        )
        checks.append(
            _doctor_check(
                "spack_version",
                "ok" if completed.returncode == 0 else "error",
                completed.stdout.strip() or completed.stderr.strip() or str(executable),
            )
        )

    checks.append(
        _doctor_check(
            "spack_user_config_path",
            "ok" if user_config_path.exists() else "warn",
            str(user_config_path),
            hint="Run fpp-spack init to create the local config directory.",
        )
    )
    checks.append(
        _doctor_check(
            "spack_user_cache_path",
            "ok" if user_cache_path.exists() else "warn",
            str(user_cache_path),
            hint="Run fpp-spack init to create the local cache/view directory.",
        )
    )

    selected_environment = None
    if args.env:
        try:
            manifest = _find_environment_manifest(root, args.env)
            selected_environment = _environment_payload(root, manifest, user_cache_path=user_cache_path)
            checks.append(_doctor_check("selected_environment", "ok", str(manifest.parent)))
        except Exception as exc:  # noqa: BLE001
            checks.append(_doctor_check("selected_environment", "error", str(exc)))

    errors = sum(1 for check in checks if check["status"] == "error")
    warnings = sum(1 for check in checks if check["status"] == "warn")
    ok = errors == 0 and (warnings == 0 or not args.strict)
    payload = {
        "ok": ok,
        "repo_root": str(repo_root),
        "spack_metadata_root": str(metadata_root),
        "spack_root": str(spack_root),
        "spack_user_config_path": str(user_config_path),
        "spack_user_cache_path": str(user_cache_path),
        "checks": checks,
        "summary": {
            "errors": errors,
            "warnings": warnings,
            "strict": args.strict,
        },
    }
    if selected_environment is not None:
        payload["environment"] = selected_environment
    if args.json:
        print(json.dumps(payload, indent=2))
    else:
        _print_doctor_human(payload)
    return 0 if ok else 1


def _activation_script(
    *,
    repo_root: Path,
    environment_root: Path,
    spack_root: Path,
    user_config_path: Path,
    user_cache_path: Path,
) -> str:
    return "\n".join(
        [
            "# Generated by fpp-spack activate.",
            f"export FEELPP_REPO_ROOT={shell_quote(repo_root)}",
            f"export SPACK_ROOT={shell_quote(spack_root)}",
            f"export SPACK_USER_CONFIG_PATH={shell_quote(user_config_path)}",
            f"export SPACK_USER_CACHE_PATH={shell_quote(user_cache_path)}",
            'if [ -f "$SPACK_ROOT/share/spack/setup-env.sh" ]; then',
            '  . "$SPACK_ROOT/share/spack/setup-env.sh"',
            "fi",
            "if command -v spack >/dev/null 2>&1; then",
            f"  eval \"$(spack env activate --sh {shell_quote(environment_root)})\"",
            "else",
            "  echo 'fpp-spack: spack command not found; run fpp-spack init --install-spack or set SPACK_ROOT' >&2",
            "  return 1 2>/dev/null || exit 1",
            "fi",
            "",
        ]
    )


def command_spack_activate(args: argparse.Namespace) -> int:
    repo_root = resolve_repo_root(args.repo_root)
    root = environments_root(repo_root)
    manifest = _find_environment_manifest(root, args.name)
    user_config_path = resolve_user_config_path(repo_root, args.user_config_path)
    user_cache_path = resolve_user_cache_path(repo_root, args.user_cache_path)
    spack_root = resolve_spack_root(repo_root, args.spack_root)
    sys.stdout.write(
        _activation_script(
            repo_root=repo_root,
            environment_root=manifest.parent,
            spack_root=spack_root,
            user_config_path=user_config_path,
            user_cache_path=user_cache_path,
        )
    )
    return 0


def register_local_commands(
    subparsers: argparse._SubParsersAction[argparse.ArgumentParser],
) -> None:
    doctor_parser = subparsers.add_parser("doctor", help="Check local Spack readiness")
    _add_repo_root_argument(doctor_parser)
    _add_local_path_arguments(doctor_parser)
    doctor_parser.add_argument("--env", help="Environment name or short alias to validate")
    doctor_parser.add_argument(
        "--strict",
        action="store_true",
        help="Return an error when warnings are present",
    )
    doctor_parser.add_argument(
        "--json",
        action="store_true",
        help="Print the machine-readable JSON doctor payload",
    )
    doctor_parser.set_defaults(func=command_spack_doctor)

    init_parser = subparsers.add_parser("init", help="Prepare local Spack paths and config")
    _add_repo_root_argument(init_parser)
    _add_local_path_arguments(init_parser)
    init_parser.add_argument("--build-jobs", type=int, default=16, help="Default Spack build_jobs")
    init_parser.add_argument("--padded-length", type=int, default=128, help="install_tree padded_length")
    init_parser.add_argument("--install-spack", action="store_true", help="Clone Spack when missing")
    init_parser.add_argument("--spack-url", default=DEFAULT_SPACK_URL, help="Git URL used with --install-spack")
    init_parser.add_argument("--spack-ref", help="Git branch/tag used with --install-spack")
    init_parser.add_argument(
        "--install-spack-packages",
        action="store_true",
        help="Clone spack/spack-packages when missing",
    )
    init_parser.add_argument("--spack-packages-root", help="spack-packages checkout root")
    init_parser.add_argument(
        "--spack-packages-url",
        default=DEFAULT_SPACK_PACKAGES_URL,
        help="Git URL used with --install-spack-packages",
    )
    init_parser.add_argument("--spack-packages-ref", help="Git branch/tag used with --install-spack-packages")
    init_parser.add_argument("--force", action="store_true", help="Overwrite generated config files")
    init_parser.add_argument("--dry-run", action="store_true", help="Show intended setup without writing")
    init_parser.set_defaults(func=command_spack_init)

    list_parser = subparsers.add_parser("list", help="List Feel++ Spack environments and views")
    _add_repo_root_argument(list_parser)
    list_parser.add_argument("--user-cache-path", help="SPACK_USER_CACHE_PATH used to resolve views")
    list_parser.set_defaults(func=command_spack_env_list)

    activate_parser = subparsers.add_parser("activate", help="Print shell code to activate a Spack environment")
    _add_repo_root_argument(activate_parser)
    _add_local_path_arguments(activate_parser)
    activate_parser.add_argument("name", help="Environment name or short alias, for example openmpi")
    activate_parser.set_defaults(func=command_spack_activate)
